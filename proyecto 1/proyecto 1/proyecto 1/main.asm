BLOQ_INC		:	.byte 1
BLOQ_DEC		:	.byte 1

MULTIPLEXOR		:	.byte 1
DISP_VALUE		:	.byte 1

UN_MIN			:	.byte 1
DEC_MIN			:	.byte 1
UN_HORA			:	.byte 1
DEC_HORA		:	.byte 1

UN_DIA			:	.byte 1
DEC_DIA			:	.byte 1
UN_MES			:	.byte 1
DEC_MES			:	.byte 1

TIEMPO			:	.byte 1
ESTADO			:	.byte 1

MODE			:	.byte 1
CONTAR			:	.byte 1
MULTIPLEXION	:	.byte 1
INCREMENTAR		:	.byte 1
DECREMENTAR		:	.byte 1

UN_MIN_ALARMA	:	.byte 1
DEC_MIN_ALARMA	:	.byte 1
UN_HORA_ALARMA	:	.byte 1
DEC_HORA_ALARMA	:	.byte 1

ALARMA			:	.byte 1

.cseg
.org 0x0000
	JMP START
.org PCI0addr
	JMP PINB_ISR
.org PCI2addr
	JMP PIND_ISR
.org OVF1addr
	JMP TMR1_ISR
.org OVF0addr
	JMP TMR0_ISR

; =========================================================
; Configuración de pila
; =========================================================
	LDI		R30, LOW(RAMEND)
	OUT		SPL, R30
	LDI		R31, HIGH(RAMEND)
	OUT		SPH, R31

; =========================================================
; Tabla 7 segmentos
; bit0=a bit1=b bit2=c bit3=d bit4=e bit5=f bit6=g
; =========================================================
table7seg:
	.DB 0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07
	.DB 0x7F,0x6F,0x77,0x7C,0x39,0x5E,0x79,0x71

; =========================================================
; START
; =========================================================
START:
	CLI

	; -------------------------
	; Puerto B
	; PB0 = D8  boton modo
	; PB2 = D10 LED1
	; PB3 = D11 LED2
	; PB4 = D12 LED3
	; PB5 = D13 buzzer
	; -------------------------
	LDI		R30, (1<<DDB2)|(1<<DDB3)|(1<<DDB4)|(1<<DDB5)
	OUT		DDRB, R30
	LDI		R30, (1<<PB0)
	OUT		PORTB, R30

	; -------------------------
	; Puerto C
	; PC0..PC5 = a..f
	; -------------------------
	LDI		R30, (1<<DDC0)|(1<<DDC1)|(1<<DDC2)|(1<<DDC3)|(1<<DDC4)|(1<<DDC5)
	OUT		DDRC, R30
	CLR		R30
	OUT		PORTC, R30

	; -------------------------
	; Puerto D
	; PD0 = decrementar
	; PD1 = incrementar
	; PD2 = dp
	; PD3..PD6 = digitos
	; PD7 = g
	; -------------------------
	LDI		R30, (1<<DDD2)|(1<<DDD3)|(1<<DDD4)|(1<<DDD5)|(1<<DDD6)|(1<<DDD7)
	OUT		DDRD, R30
	LDI		R30, (1<<PD0)|(1<<PD1)|(1<<PD3)|(1<<PD4)|(1<<PD5)|(1<<PD6)
	OUT		PORTD, R30

	; Apagar UART
	CLR		R30
	STS		UCSR0B, R30

	RCALL	INIT_TMR1
	RCALL	INIT_TMR0

	CLR		PUNTO
	LDI		R30, 0b00001110
	STS		MULTIPLEXOR, R30

	CLR		R30
	STS		UN_MIN, R30
	STS		DEC_MIN, R30
	STS		UN_HORA, R30
	STS		DEC_HORA, R30
	STS		DEC_DIA, R30
	STS		DEC_MES, R30
	STS		DISP_VALUE, R30

	STS		UN_MIN_ALARMA, R30
	STS		DEC_MIN_ALARMA, R30
	STS		UN_HORA_ALARMA, R30
	STS		DEC_HORA_ALARMA, R30

	STS		CONTAR, R30
	STS		MODE, R30
	STS		MULTIPLEXION, R30
	STS		INCREMENTAR, R30
	STS		DECREMENTAR, R30
	STS		ALARMA, R30
	STS		TIEMPO, R30

	STS		BLOQ_MODO, R30
	STS		BLOQ_INC, R30
	STS		BLOQ_DEC, R30

	LDI		R30, 0x01
	STS		UN_DIA, R30
	STS		UN_MES, R30

	IN		R30, PIND
	ANDI	R30, 0b00000011
	STS		ESTADO, R30

	; Interrupciones
	LDI		R30, (1<<TOIE1)
	STS		TIMSK1, R30

	LDI		R30, (1<<TOIE0)
	STS		TIMSK0, R30

	LDI		R30, (1<<PCIE2)|(1<<PCIE0)
	STS		PCICR, R30

	LDI		R30, (1<<PCINT16)|(1<<PCINT17)
	STS		PCMSK2, R30

	LDI		R30, (1<<PCINT0)
	STS		PCMSK0, R30

	SEI

; =========================================================
; MAIN LOOP
; =========================================================
MAIN_LOOP:
VER_MODE0:
	LDS		R30, MODE
	CPI		R30, 0
	BRNE	VER_MODE1
	RJMP	MODE_0

VER_MODE1:
	CPI		R30, 1
	BRNE	VER_MODE2
	RJMP	MODE_1

VER_MODE2:
	CPI		R30, 2
	BRNE	VER_MODE3
	RJMP	MODE_2

VER_MODE3:
	CPI		R30, 3
	BRNE	VER_MODE4
	RJMP	MODE_3

VER_MODE4:
	CPI		R30, 4
	BRNE	VER_MODE5
	RJMP	MODE_4

VER_MODE5:
	CPI		R30, 5
	BRNE	VER_MODE6
	RJMP	MODE_5

VER_MODE6:
	CPI		R30, 6
	BRNE	IR_MULTIPLEX
	RJMP	MODE_6

IR_MULTIPLEX:
	RJMP	MULTIPLEXACION

; =========================================================
; MOSTRAR
; =========================================================
MOSTRAR:
	LDS		R26, DISP_VALUE
	LDI		ZH, HIGH(table7seg<<1)
	LDI		ZL, LOW(table7seg<<1)
	ADD		ZL, R26
	LPM		R27, Z

	MOV		R28, R27
	ANDI	R28, 0b00111111
	OUT		PORTC, R28

	LDI		R28, 0b00000011
	MOV		R29, PUNTO
	OR		R28, R29

	LDS		R29, MULTIPLEXOR
	LSL		R29
	LSL		R29
	LSL		R29
	ANDI	R29, 0b01111000
	OR		R28, R29

	SBRC	R27, 6
	ORI		R28, 0b10000000

	OUT		PORTD, R28

	LDS		R28, MODE
	LSL		R28
	LSL		R28
	ORI		R28, 0x01
	LDS		R29, ALARMA
	CPI		R29, 1
	BRNE	MOSTRAR_MODO
	ORI		R28, 0b00100000

MOSTRAR_MODO:
	OUT		PORTB, R28
	RJMP	MAIN_LOOP

; =========================================================
; MODO 0 = reloj normal
