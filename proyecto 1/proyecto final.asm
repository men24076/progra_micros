.include "M328PDEF.inc"

.equ	TMR0_VALUE	=	6
.equ	TMR1_VALUE	=	0x85EE
.equ	MAX_MODES	=	6
.def	PUNTO		=	R25

.dseg
CERROJO_MODO	:	.byte 1
CERROJO_MAS		:	.byte 1
CERROJO_MENOS	:	.byte 1

SCAN_SEL		:	.byte 1
SCAN_VAL		:	.byte 1

MIN_U_ACT		:	.byte 1
MIN_D_ACT		:	.byte 1
HOR_U_ACT		:	.byte 1
HOR_D_ACT		:	.byte 1

DIA_U_ACT		:	.byte 1
DIA_D_ACT		:	.byte 1
MES_U_ACT		:	.byte 1
MES_D_ACT		:	.byte 1

TICK_05S		:	.byte 1
EST_BTN			:	.byte 1

VISTA_ACT		:	.byte 1
FLAG_MINUTO		:	.byte 1
FLAG_SCAN		:	.byte 1
FLAG_MAS		:	.byte 1
FLAG_MENOS		:	.byte 1

ALM_MIN_U		:	.byte 1
ALM_MIN_D		:	.byte 1
ALM_HOR_U		:	.byte 1
ALM_HOR_D		:	.byte 1

FLAG_ALARMA		:	.byte 1

.cseg
.org 0x0000
	JMP START
.org PCI0addr
	JMP PINB_ISR
.org PCI2addr
	JMP PIND_ISR
.org OVF1addr
	JMP TMR1_ISR
.org OVF0addr
	JMP TMR0_ISR

; =========================================================
; Pila
; =========================================================
	LDI		R16, LOW(RAMEND)
	OUT		SPL, R16
	LDI		R16, HIGH(RAMEND)
	OUT		SPH, R16

; =========================================================
; Tabla 7 segmentos
; bit0=a bit1=b bit2=c bit3=d bit4=e bit5=f bit6=g
; =========================================================
TABLA7SEG:
	.DB 0x3F,0x06,0x5B,0x4F,0x66,0x6D,0x7D,0x07
	.DB 0x7F,0x6F,0x77,0x7C,0x39,0x5E,0x79,0x71

; =========================================================
; START
; =========================================================
START:
	CLI
	RCALL INIT_IO
	RCALL INIT_USART
	RCALL INIT_TMR1
	RCALL INIT_TMR0
	RCALL INIT_RAM
	RCALL INIT_INTERRUPTS
	SEI

; =========================================================
; MAIN LOOP
; =========================================================
MAIN_LOOP:
	LDS		R16, VISTA_ACT

CHECK_MODE0:
	CPI		R16, 0
	BRNE	CHECK_MODE1
	RJMP	MODE_0

CHECK_MODE1:
	CPI		R16, 1
	BRNE	CHECK_MODE2
	RJMP	MODE_1

CHECK_MODE2:
	CPI		R16, 2
	BRNE	CHECK_MODE3
	RJMP	MODE_2

CHECK_MODE3:
	CPI		R16, 3
	BRNE	CHECK_MODE4
	RJMP	MODE_3

CHECK_MODE4:
	CPI		R16, 4
	BRNE	CHECK_MODE5
	RJMP	MODE_4

CHECK_MODE5:
	CPI		R16, 5
	BRNE	CHECK_MODE6
	RJMP	MODE_5

CHECK_MODE6:
	CPI		R16, 6
	BRNE	GO_SCAN
	RJMP	MODE_6

GO_SCAN:
	RJMP	MULTIPLEXACION

; =========================================================
; Inicialización
; =========================================================
INIT_IO:
	; PB0 = D8  boton modo
	; PB2 = D10 LED1
	; PB3 = D11 LED2
	; PB4 = D12 LED3
	; PB5 = D13 buzzer
	LDI		R16, (1<<DDB2)|(1<<DDB3)|(1<<DDB4)|(1<<DDB5)
	OUT		DDRB, R16
	LDI		R16, (1<<PB0)
	OUT		PORTB, R16

	; PC0..PC5 = a..f
	LDI		R16, (1<<DDC0)|(1<<DDC1)|(1<<DDC2)|(1<<DDC3)|(1<<DDC4)|(1<<DDC5)
	OUT		DDRC, R16
	CLR		R16
	OUT		PORTC, R16

	; PD0 = decrementar
	; PD1 = incrementar
	; PD2 = dp
	; PD3..PD6 = digitos
	; PD7 = g
	LDI		R16, (1<<DDD2)|(1<<DDD3)|(1<<DDD4)|(1<<DDD5)|(1<<DDD6)|(1<<DDD7)
	OUT		DDRD, R16
	LDI		R16, (1<<PD0)|(1<<PD1)|(1<<PD3)|(1<<PD4)|(1<<PD5)|(1<<PD6)
	OUT		PORTD, R16
	RET

INIT_USART:
	CLR		R16
	STS		UCSR0B, R16
	RET

INIT_RAM:
	CLR		PUNTO

	LDI		R16, 0b00001110
	STS		SCAN_SEL, R16

	CLR		R16
	STS		MIN_U_ACT, R16
	STS		MIN_D_ACT, R16
	STS		HOR_U_ACT, R16
	STS		HOR_D_ACT, R16
	STS		DIA_D_ACT, R16
	STS		MES_D_ACT, R16
	STS		SCAN_VAL, R16

	STS		ALM_MIN_U, R16
	STS		ALM_MIN_D, R16
	STS		ALM_HOR_U, R16
	STS		ALM_HOR_D, R16

	STS		FLAG_MINUTO, R16
	STS		VISTA_ACT, R16
	STS		FLAG_SCAN, R16
	STS		FLAG_MAS, R16
	STS		FLAG_MENOS, R16
	STS		FLAG_ALARMA, R16
	STS		TICK_05S, R16

	STS		CERROJO_MODO, R16
	STS		CERROJO_MAS, R16
	STS		CERROJO_MENOS, R16

	LDI		R16, 1
	STS		DIA_U_ACT, R16
	STS		MES_U_ACT, R16

	IN		R16, PIND
	ANDI	R16, 0b00000011
	STS		EST_BTN, R16
	RET

INIT_INTERRUPTS:
	LDI		R16, (1<<TOIE1)
	STS		TIMSK1, R16

	LDI		R16, (1<<TOIE0)
	STS		TIMSK0, R16

	LDI		R16, (1<<PCIE2)|(1<<PCIE0)
	STS		PCICR, R16

	LDI		R16, (1<<PCINT16)|(1<<PCINT17)
	STS		PCMSK2, R16

	LDI		R16, (1<<PCINT0)
	STS		PCMSK0, R16
	RET

; =========================================================
; TIMERS
; =========================================================
INIT_TMR1:
	CLR		R16
	STS		TCCR1A, R16
	LDI		R16, (1<<CS12)
	STS		TCCR1B, R16
	LDI		R16, HIGH(TMR1_VALUE)
	STS		TCNT1H, R16
	LDI		R16, LOW(TMR1_VALUE)
	STS		TCNT1L, R16
	RET

INIT_TMR0:
	CLR		R16
	OUT		TCCR0A, R16
	LDI		R16, (1<<CS02)
	OUT		TCCR0B, R16
	LDI		R16, TMR0_VALUE
	OUT		TCNT0, R16
	RET

; =========================================================
; MOSTRAR
; =========================================================
MOSTRAR:
	LDS		R16, SCAN_VAL
	LDI		ZH, HIGH(TABLA7SEG<<1)
	LDI		ZL, LOW(TABLA7SEG<<1)
	ADD		ZL, R16
	LPM		R17, Z

	; a..f -> PORTC
	MOV		R18, R17
	ANDI	R18, 0b00111111
	OUT		PORTC, R18

	; base PORTD
	LDI		R18, 0b00000011
	MOV		R19, PUNTO
	OR		R18, R19

	; digitos
	LDS		R19, SCAN_SEL
	LSL		R19
	LSL		R19
	LSL		R19
	ANDI	R19, 0b01111000
	OR		R18, R19

	; g
	SBRC	R17, 6
	ORI		R18, 0b10000000

	OUT		PORTD, R18

	; leds y buzzer
	LDS		R18, VISTA_ACT
	LSL		R18
	LSL		R18
	ORI		R18, 0x01

	LDS		R19, FLAG_ALARMA
	CPI		R19, 1
	BRNE	END_MOSTRAR
	ORI		R18, 0b00100000

END_MOSTRAR:
	OUT		PORTB, R18
	RJMP	MAIN_LOOP

; =========================================================
; Helpers de datos
; =========================================================
LOAD_CLOCK_DATE:
	LDS		R17, MIN_U_ACT
	LDS		R18, MIN_D_ACT
	LDS		R19, HOR_U_ACT
	LDS		R20, HOR_D_ACT
	LDS		R21, DIA_U_ACT
	LDS		R22, DIA_D_ACT
	LDS		R23, MES_U_ACT
	LDS		R24, MES_D_ACT
	RET

SAVE_CLOCK_DATE:
	STS		MIN_U_ACT, R17
	STS		MIN_D_ACT, R18
	STS		HOR_U_ACT, R19
	STS		HOR_D_ACT, R20
	STS		DIA_U_ACT, R21
	STS		DIA_D_ACT, R22
	STS		MES_U_ACT, R23
	STS		MES_D_ACT, R24
	RET

CHECK_ALARM_MATCH:
	LDS		R16, MIN_U_ACT
	LDS		R26, ALM_MIN_U
	CP		R16, R26
	BRNE	ALARM_NO

	LDS		R16, MIN_D_ACT
	LDS		R26, ALM_MIN_D
	CP		R16, R26
	BRNE	ALARM_NO

	LDS		R16, HOR_U_ACT
	LDS		R26, ALM_HOR_U
	CP		R16, R26
	BRNE	ALARM_NO

	LDS		R16, HOR_D_ACT
	LDS		R26, ALM_HOR_D
	CP		R16, R26
	BRNE	ALARM_NO

	LDI		R16, 1
	STS		FLAG_ALARMA, R16
ALARM_NO:
	RET

; =========================================================
; Rutina interna para avanzar fecha
; usa R21-R24
; =========================================================
NEXT_DATE:
	CPI		R24, 1
	BREQ	ND_ULTIMOS
	RJMP	ND_PRIMEROS

ND_ULTIMOS:
	CPI		R23, 1
	BRNE	ND_ULT_NO_10
	RJMP	ND_30
ND_ULT_NO_10:
	RJMP	ND_31

ND_PRIMEROS:
	CPI		R23, 2
	BREQ	ND_28
	CPI		R23, 4
	BREQ	ND_30
	CPI		R23, 6
	BREQ	ND_30
	CPI		R23, 9
	BREQ	ND_30
	RJMP	ND_31

ND_28:
	INC		R21
	CPI		R21, 9
	BREQ	ND_28_CHECK
	CPI		R21, 10
	BRNE	ND_END
	CLR		R21
	INC		R22
ND_28_CHECK:
	CPI		R21, 9
	BRNE	ND_END
	CPI		R22, 2
	BRNE	ND_END
	LDI		R21, 1
	CLR		R22
	RJMP	ND_NEXT_MONTH

ND_30:
	INC		R21
	CPI		R21, 1
	BREQ	ND_30_CHECK
	CPI		R21, 10
	BRNE	ND_END
	CLR		R21
	INC		R22
ND_30_CHECK:
	CPI		R21, 1
	BRNE	ND_END
	CPI		R22, 3
	BRNE	ND_END
	LDI		R21, 1
	CLR		R22
	RJMP	ND_NEXT_MONTH

ND_31:
	INC		R21
	CPI		R21, 2
	BREQ	ND_31_CHECK
	CPI		R21, 10
	BRNE	ND_END
	CLR		R21
	INC		R22
ND_31_CHECK:
	CPI		R21, 2
	BRNE	ND_END
	CPI		R22, 3
	BRNE	ND_END
	LDI		R21, 1
	CLR		R22
	RJMP	ND_NEXT_MONTH

ND_NEXT_MONTH:
	INC		R23
	CPI		R23, 3
	BREQ	ND_DIC_CHECK
	CPI		R23, 10
	BRNE	ND_END
	CLR		R23
	INC		R24
ND_DIC_CHECK:
	CPI		R23, 3
	BRNE	ND_END
	CPI		R24, 1
	BRNE	ND_END
	LDI		R23, 1
	CLR		R24

ND_END:
	RET

; =========================================================
; MODO 0 = reloj normal
; =========================================================
MODE_0:
	CLI
	LDS		R16, FLAG_MINUTO
	CPI		R16, 1
	BRNE	M0_NO_COUNT
	CLR		R16
	STS		FLAG_MINUTO, R16
	SEI
	RJMP	M0_COUNT
M0_NO_COUNT:
	SEI
	RJMP	M0_CHECK_BUTTONS

M0_COUNT:
	RCALL	LOAD_CLOCK_DATE

	INC		R17
	CPI		R17, 10
	BRNE	M0_STORE
	CLR		R17

	INC		R18
	CPI		R18, 6
	BRNE	M0_STORE
	CLR		R18

	INC		R19
	CPI		R19, 10
	BRNE	M0_H24
	CLR		R19
	INC		R20

M0_H24:
	CPI		R20, 2
	BRNE	M0_STORE
	CPI		R19, 4
	BRNE	M0_STORE
	CLR		R19
	CLR		R20
	RCALL	NEXT_DATE

M0_STORE:
	RCALL	SAVE_CLOCK_DATE
	RCALL	CHECK_ALARM_MATCH

M0_CHECK_BUTTONS:
	CLI
	LDS		R16, FLAG_MAS
	CPI		R16, 1
	BRNE	M0_CHECK_MINUS
	CLR		R16
	STS		FLAG_MAS, R16
	SEI
	RJMP	M0_MUTE
M0_CHECK_MINUS:
	SEI
	CLI
	LDS		R16, FLAG_MENOS
	CPI		R16, 1
	BRNE	M0_EXIT
	CLR		R16
	STS		FLAG_MENOS, R16
	SEI
	RJMP	M0_MUTE
M0_EXIT:
	SEI
	RJMP	MULTIPLEXACION

M0_MUTE:
	CLR		R16
	STS		FLAG_ALARMA, R16
	RJMP	MULTIPLEXACION

; =========================================================
; MODO 1 = ajustar minutos
; =========================================================
MODE_1:
	CLI
	LDS		R16, FLAG_MAS
	CPI		R16, 1
	BRNE	M1_DEC_CHECK
	CLR		R16
	STS		FLAG_MAS, R16
	SEI
	RJMP	M1_INC
M1_DEC_CHECK:
	SEI
	CLI
	LDS		R16, FLAG_MENOS
	CPI		R16, 1
	BRNE	M1_END
	CLR		R16
	STS		FLAG_MENOS, R16
	SEI
	RJMP	M1_DEC
M1_END:
	SEI
	RJMP	MULTIPLEXACION

M1_INC:
	LDS		R17, MIN_U_ACT
	LDS		R18, MIN_D_ACT
	INC		R17
	CPI		R17, 10
	BRNE	M1_SAVE_INC
	CLR		R17
	INC		R18
	CPI		R18, 6
	BRNE	M1_SAVE_INC
	CLR		R18
M1_SAVE_INC:
	STS		MIN_U_ACT, R17
	STS		MIN_D_ACT, R18
	RJMP	MULTIPLEXACION

M1_DEC:
	LDS		R17, MIN_U_ACT
	LDS		R18, MIN_D_ACT
	DEC		R17
	CPI		R17, 255
	BRNE	M1_SAVE_DEC
	LDI		R17, 9
	DEC		R18
	CPI		R18, 255
	BRNE	M1_SAVE_DEC
	LDI		R18, 5
M1_SAVE_DEC:
	STS		MIN_U_ACT, R17
	STS		MIN_D_ACT, R18
	RJMP	MULTIPLEXACION

; =========================================================
; MODO 2 = ajustar horas
; =========================================================
MODE_2:
	CLI
	LDS		R16, FLAG_MAS
	CPI		R16, 1
	BRNE	M2_DEC_CHECK
	CLR		R16
	STS		FLAG_MAS, R16
	SEI
	RJMP	M2_INC
M2_DEC_CHECK:
	SEI
	CLI
	LDS		R16, FLAG_MENOS
	CPI		R16, 1
	BRNE	M2_END
	CLR		R16
	STS		FLAG_MENOS, R16
	SEI
	RJMP	M2_DEC
M2_END:
	SEI
	RJMP	MULTIPLEXACION

M2_INC:
	LDS		R17, HOR_U_ACT
	LDS		R18, HOR_D_ACT
	INC		R17
	CPI		R17, 10
	BRNE	M2_REV24
	CLR		R17
	INC		R18
M2_REV24:
	CPI		R18, 2
	BRNE	M2_SAVE_INC
	CPI		R17, 4
	BRNE	M2_SAVE_INC
	CLR		R17
	CLR		R18
M2_SAVE_INC:
	STS		HOR_U_ACT, R17
	STS		HOR_D_ACT, R18
	RJMP	MULTIPLEXACION

M2_DEC:
	LDS		R17, HOR_U_ACT
	LDS		R18, HOR_D_ACT
	DEC		R17
	CPI		R17, 255
	BRNE	M2_SAVE_DEC
	LDI		R17, 9
	DEC		R18
	CPI		R18, 255
	BRNE	M2_SAVE_DEC
	LDI		R17, 3
	LDI		R18, 2
M2_SAVE_DEC:
	STS		HOR_U_ACT, R17
	STS		HOR_D_ACT, R18
	RJMP	MULTIPLEXACION

; =========================================================
; MODO 3 = ajustar mes
; =========================================================
MODE_3:
	CLI
	LDS		R16, FLAG_MAS
	CPI		R16, 1
	BRNE	M3_DEC_CHECK
	CLR		R16
	STS		FLAG_MAS, R16
	SEI
	RJMP	M3_INC
M3_DEC_CHECK:
	SEI
	CLI
	LDS		R16, FLAG_MENOS
	CPI		R16, 1
	BRNE	M3_END
	CLR		R16
	STS		FLAG_MENOS, R16
	SEI
	RJMP	M3_DEC
M3_END:
	SEI
	RJMP	MULTIPLEXACION

M3_INC:
	LDS		R17, MES_U_ACT
	LDS		R18, MES_D_ACT
	INC		R17
	CPI		R17, 10
	BRNE	M3_REV12
	CLR		R17
	INC		R18
M3_REV12:
	CPI		R18, 1
	BRNE	M3_SAVE_INC
	CPI		R17, 3
	BRNE	M3_SAVE_INC
	LDI		R17, 1
	CLR		R18
M3_SAVE_INC:
	STS		MES_U_ACT, R17
	STS		MES_D_ACT, R18
	RJMP	MULTIPLEXACION

M3_DEC:
	LDS		R17, MES_U_ACT
	LDS		R18, MES_D_ACT
	CPI		R17, 1
	BRNE	M3_DEC_NORMAL
	CPI		R18, 0
	BRNE	M3_DEC_NORMAL
	LDI		R17, 2
	LDI		R18, 1
	RJMP	M3_SAVE_DEC
M3_DEC_NORMAL:
	DEC		R17
	CPI		R17, 255
	BRNE	M3_SAVE_DEC
	LDI		R17, 9
	DEC		R18
M3_SAVE_DEC:
	STS		MES_U_ACT, R17
	STS		MES_D_ACT, R18
	RJMP	MULTIPLEXACION

; =========================================================
; MODO 4 = ajustar día
; =========================================================
MODE_4:
	CLI
	LDS		R16, FLAG_MAS
	CPI		R16, 1
	BRNE	M4_DEC_CHECK
	CLR		R16
	STS		FLAG_MAS, R16
	SEI
	RJMP	M4_INC
M4_DEC_CHECK:
	SEI
	CLI
	LDS		R16, FLAG_MENOS
	CPI		R16, 1
	BRNE	M4_END
	CLR		R16
	STS		FLAG_MENOS, R16
	SEI
	RJMP	M4_DEC
M4_END:
	SEI
	RJMP	MULTIPLEXACION

M4_INC:
	LDS		R16, DIA_U_ACT
	LDS		R17, DIA_D_ACT
	LDS		R18, MES_U_ACT
	LDS		R19, MES_D_ACT

	CPI		R19, 1
	BREQ	M4_GROUP_10_12
	RJMP	M4_GROUP_01_09

M4_GROUP_10_12:
	CPI		R18, 1
	BRNE	M4_31D
	RJMP	M4_30D

M4_GROUP_01_09:
	CPI		R18, 2
	BREQ	M4_28D
	CPI		R18, 4
	BREQ	M4_30D
	CPI		R18, 6
	BREQ	M4_30D
	CPI		R18, 9
	BREQ	M4_30D
	RJMP	M4_31D

M4_28D:
	INC		R16
	CPI		R16, 9
	BREQ	M4_28CHK
	CPI		R16, 10
	BRNE	M4_SAVE
	CLR		R16
	INC		R17
M4_28CHK:
	CPI		R16, 9
	BRNE	M4_SAVE
	CPI		R17, 2
	BRNE	M4_SAVE
	LDI		R16, 1
	CLR		R17
	RJMP	M4_SAVE

M4_30D:
	INC		R16
	CPI		R16, 1
	BREQ	M4_30CHK
	CPI		R16, 10
	BRNE	M4_SAVE
	CLR		R16
	INC		R17
M4_30CHK:
	CPI		R16, 1
	BRNE	M4_SAVE
	CPI		R17, 3
	BRNE	M4_SAVE
	LDI		R16, 1
	CLR		R17
	RJMP	M4_SAVE

M4_31D:
	INC		R16
	CPI		R16, 2
	BREQ	M4_31CHK
	CPI		R16, 10
	BRNE	M4_SAVE
	CLR		R16
	INC		R17
M4_31CHK:
	CPI		R16, 2
	BRNE	M4_SAVE
	CPI		R17, 3
	BRNE	M4_SAVE
	LDI		R16, 1
	CLR		R17

M4_SAVE:
	STS		DIA_U_ACT, R16
	STS		DIA_D_ACT, R17
	STS		MES_U_ACT, R18
	STS		MES_D_ACT, R19
	RJMP	MULTIPLEXACION

M4_DEC:
	LDS		R16, DIA_U_ACT
	LDS		R17, DIA_D_ACT
	LDS		R18, MES_U_ACT
	LDS		R19, MES_D_ACT

	CPI		R16, 1
	BRNE	M4_DEC_NORMAL
	CPI		R17, 0
	BRNE	M4_DEC_NORMAL

	CPI		R19, 1
	BREQ	M4_DEC_G1012
	RJMP	M4_DEC_G0109

M4_DEC_G1012:
	CPI		R18, 1
	BRNE	M4_LOAD31
	RJMP	M4_LOAD30

M4_DEC_G0109:
	CPI		R18, 2
	BREQ	M4_LOAD28
	CPI		R18, 4
	BREQ	M4_LOAD30
