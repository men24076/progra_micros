	IN		R16, SREG
	PUSH	R16
	PUSH	R17
	PUSH	R18

	IN		R16, PIND
	ANDI	R16, 0b00000011

	; incrementar
	LDS		R17, CERROJO_MAS
	CPI		R17, 0
	BREQ	PD_REV_INC

	SBRS	R16, 1
	RJMP	PD_REV_DEC_LOCK

	CLR		R17
	STS		CERROJO_MAS, R17
	RJMP	PD_REV_DEC_LOCK

