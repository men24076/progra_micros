	LDI		R18, 1
	STS		FLAG_MAS, R18
	STS		CERROJO_MAS, R18

	; decrementar
PD_REV_DEC_LOCK:
	LDS		R17, CERROJO_MENOS
	CPI		R17, 0
	BREQ	PD_REV_DEC

	SBRS	R16, 0
	RJMP	PD_SALIDA

	CLR		R17
