PINB_ISR:
	PUSH	R16
	IN		R16, SREG
	PUSH	R16
	PUSH	R17

	RCALL	DELAY_BOTON
	IN		R16, PINB

	; MODO en PB0
	SBRS	R16, PB0
	RJMP	AUMENTAR_MODE

	; HORA + en PB3
	SBRS	R16, PB3
	RJMP	SET_INCREMENTAR

	; HORA - en PB4
	SBRS	R16, PB4
	RJMP	SET_DECREMENTAR

	RJMP	EXIT_PINB_ISR

